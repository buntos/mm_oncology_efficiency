# HELPERS
# ============================================================

def load_case_metrics(case_id):

    path = (
        SOURCE_ROOT
        / case_id
        / "candidate_metrics.csv"
    )


    if not path.exists():

        raise FileNotFoundError(
            f"candidate_metrics.csv not found for "
            f"{case_id}: {path}"
        )


    metrics = pd.read_csv(
        path
    )


    required_columns = [
        "candidate_order",
        "final_tissue_fraction",
        "background_fraction",
        "white_fraction",
        "artifact_reject",
    ]


    missing = [
        column
        for column
        in required_columns
        if column not in metrics.columns
    ]


    if missing:

        raise RuntimeError(
            f"{case_id}: missing required columns: "
            f"{missing}"
        )


    metrics[
        "artifact_reject"
    ] = (
        metrics[
            "artifact_reject"
        ]
        .astype(str)
        .str.lower()
        .map(
            {
                "true": True,
                "false": False,
                "1": True,
                "0": False,
            }
        )
    )


    if (
        metrics[
            "artifact_reject"
        ]
        .isna()
        .any()
    ):

        raise RuntimeError(
            f"{case_id}: artifact_reject contains "
            f"unrecognized values."
        )


    metrics = metrics.sort_values(
        "candidate_order"
    ).reset_index(
        drop=True
    )


    return metrics


def calculate_quantile_rows(
    case_id,
    values,
    subset_name,
):

    values = pd.Series(
        values
    ).dropna()


    if values.empty:
        return []


    quantiles = [
        0.00,
        0.01,
        0.05,
        0.10,
        0.25,
        0.50,
        0.75,
        0.90,
        0.95,
        0.99,
        1.00,
    ]


    rows = []


    for quantile in quantiles:

        rows.append(
            {
                "case_submitter_id": (
                    case_id
                ),

                "subset": (
                    subset_name
                ),

                "quantile": float(
                    quantile
                ),

                "final_tissue_fraction": float(
                    values.quantile(
                        quantile
                    )
                ),
            }
        )


    return rows


def eligible_without_tissue_threshold(
    metrics,
    white_threshold,
):

    mask = (
        (
            metrics[
                "background_fraction"
            ]
            <=
            BACKGROUND_THRESHOLD
        )
        &
        (
            metrics[
                "white_fraction"
            ]
            <=
            white_threshold
        )
        &
        (
            ~metrics[
                "artifact_reject"
            ]
        )
    )


    return metrics[
        mask
    ].copy()


def calculate_critical_tissue_threshold(
    eligible,
):

    if len(eligible) < TARGET_TILES:
        return None


    values = (
        eligible[
            "final_tissue_fraction"
        ]
        .sort_values(
            ascending=False
        )
        .reset_index(
            drop=True
        )
    )


    return float(
        values.iloc[
            TARGET_TILES - 1
        ]
    )


def run_tissue_sweep(
    case_id,
    metrics,
    white_threshold,
):

    rows = []


    for tissue_threshold in (
        TISSUE_THRESHOLDS
    ):

        mask = (
            (
                metrics[
                    "final_tissue_fraction"
                ]
                >=
                tissue_threshold
            )
            &
            (
                metrics[
                    "background_fraction"
                ]
                <=
                BACKGROUND_THRESHOLD
            )
            &
            (
                metrics[
                    "white_fraction"
                ]
                <=
                white_threshold
            )
            &
            (
                ~metrics[
                    "artifact_reject"
                ]
            )
        )


        accepted = (
            metrics[
                mask
            ]
            .sort_values(
                "candidate_order"
            )
        )


        accepted_count = int(
            len(
                accepted
            )
        )


        reached_64 = (
            accepted_count
            >=
            TARGET_TILES
        )


        if reached_64:

            checked_to_64 = int(
                accepted.iloc[
                    TARGET_TILES - 1
                ][
                    "candidate_order"
                ]
            )

        else:

            checked_to_64 = None


        rows.append(
            {
                "case_submitter_id": (
                    case_id
                ),

                "white_threshold": float(
                    white_threshold
                ),

                "background_threshold": float(
                    BACKGROUND_THRESHOLD
                ),

                "tissue_threshold": float(
                    tissue_threshold
                ),

                "accepted_tiles": (
                    accepted_count
                ),

                "reached_64": bool(
                    reached_64
                ),

                "checked_to_64": (
                    checked_to_64
                ),
            }
        )


    return rows


# ============================================================
# ANALYZE ONE CASE
# ============================================================

def analyze_case(
    case_id,
):

    print()
    print("=" * 92)

    print(
        f" {case_id}"
    )

    print("=" * 92)


    metrics = load_case_metrics(
        case_id
    )


    case_output_dir = (
        OUTPUT_ROOT
        / case_id
    )


    case_output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )


    print(
        f"Candidates loaded: "
        f"{len(metrics)}"
    )


    # ========================================================
    # GLOBAL TISSUE DISTRIBUTION
    # ========================================================

    quantile_rows = []


    quantile_rows.extend(
        calculate_quantile_rows(
            case_id=case_id,

            values=(
                metrics[
                    "final_tissue_fraction"
                ]
            ),

            subset_name=(
                "all_thumbnail_candidates"
            ),
        )
    )


    # ========================================================
    # TWO WHITE SCENARIOS
    # ========================================================

    scenario_summary_rows = []
    sweep_rows = []


    for white_threshold in (
        WHITE_THRESHOLDS
    ):

        scenario_name = (
            f"white_le_"
            f"{white_threshold:.2f}"
        )


        eligible = (
            eligible_without_tissue_threshold(
                metrics=metrics,

                white_threshold=(
                    white_threshold
                ),
            )
        )


        quantile_rows.extend(
            calculate_quantile_rows(
                case_id=case_id,

                values=(
                    eligible[
                        "final_tissue_fraction"
                    ]
                ),

                subset_name=(
                    scenario_name
                ),
            )
        )


        critical_threshold = (
            calculate_critical_tissue_threshold(
                eligible
            )
        )


        if critical_threshold is None:

            theoretically_reaches_64 = (
                False
            )

        else:

            theoretically_reaches_64 = (
                True
            )


        scenario_summary_rows.append(
            {
                "case_submitter_id": (
                    case_id
                ),

                "white_threshold": float(
                    white_threshold
                ),

                "background_threshold": float(
                    BACKGROUND_THRESHOLD
                ),

                "eligible_before_tissue_filter": int(
                    len(
                        eligible
                    )
                ),

                "can_ever_reach_64": bool(
                    theoretically_reaches_64
                ),

                "maximum_tissue_threshold_for_64": (
                    critical_threshold
                ),
            }
        )


        case_sweep_rows = (
            run_tissue_sweep(
                case_id=case_id,

                metrics=metrics,

                white_threshold=(
                    white_threshold
                ),
            )
        )


        sweep_rows.extend(
            case_sweep_rows
        )


    # ========================================================
    # SAVE CASE OUTPUTS
    # ========================================================

    quantiles = pd.DataFrame(
        quantile_rows
    )


    scenario_summary = pd.DataFrame(
        scenario_summary_rows
    )


    sweep = pd.DataFrame(
        sweep_rows
    )


    quantiles.to_csv(
        (
            case_output_dir
            /
            "final_tissue_quantiles.csv"
        ),
        index=False,
    )


    scenario_summary.to_csv(
        (
            case_output_dir
            /
            "scenario_summary.csv"
        ),
        index=False,
    )


    sweep.to_csv(
        (
            case_output_dir
            /
            "tissue_threshold_sweep.csv"
        ),
        index=False,
    )


    pivot = sweep.pivot(
        index="tissue_threshold",
        columns="white_threshold",
        values="accepted_tiles",
    ).sort_index(
        ascending=False
    )


    pivot.to_csv(
        (
            case_output_dir
            /
            "accepted_tiles_pivot.csv"
        )
    )


    # ========================================================
    # PRINT DISTRIBUTION
    # ========================================================

    all_quantiles = quantiles[
        quantiles[
            "subset"
        ]
        ==
        "all_thumbnail_candidates"
    ][
        [
            "quantile",
            "final_tissue_fraction",
        ]
    ]


    print()
    print(
        "FINAL_TISSUE_FRACTION DISTRIBUTION"
    )

    print()


    print(
        all_quantiles.to_string(
            index=False
        )
    )


    # ========================================================
    # PRINT SCENARIO SUMMARY
    # ========================================================

    print()
    print(
        "MAXIMUM POSSIBLE TISSUE THRESHOLD "
        "FOR 64 TILES"
    )

    print()


    print(
        scenario_summary.to_string(
            index=False
        )
    )


    # ========================================================
    # PRINT SWEEP
    # ========================================================

    print()
    print(
        "ACCEPTED TILES BY TISSUE THRESHOLD"
    )

    print()


    print(
        pivot.to_string()
    )


    return {
        "case_submitter_id": (
            case_id
        ),

        "candidate_count": int(
            len(
                metrics
            )
        ),

        "scenario_rows": (
            scenario_summary_rows
        ),
    }


