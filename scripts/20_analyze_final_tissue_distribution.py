FROZEN_CONFIG_PATH = (
    METADATA_ROOT
    / "frozen_audit_configuration.json"
)


def write_or_verify_frozen_config(case_ids):

    payload = {
        "audit_name": AUDIT_NAME,
        "source_audit_name": SOURCE_AUDIT_NAME,
        "case_ids": list(case_ids),

        "background_threshold": (
            BACKGROUND_THRESHOLD
        ),

        "white_thresholds": (
            WHITE_THRESHOLDS
        ),

        "tissue_thresholds": (
            TISSUE_THRESHOLDS
        ),

        "target_tiles": (
            TARGET_TILES
        ),

        "note": (
            "Local-only analysis of candidate_metrics.csv "
            "generated by script 19. "
            "No WSI download and no production modification."
        ),
    }


    if FROZEN_CONFIG_PATH.exists():

        existing = json.loads(
            FROZEN_CONFIG_PATH.read_text(
                encoding="utf-8"
            )
        )

        if existing != payload:

            raise RuntimeError(
                "Existing frozen audit configuration differs "
                "from the current script. "
                "Use a new AUDIT_NAME instead of overwriting "
                "the existing experiment."
            )

        return


    FROZEN_CONFIG_PATH.write_text(
        json.dumps(
            payload,
            indent=2,
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )


